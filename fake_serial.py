"""Scripted, deterministic serial fake for offline boundary tests."""

from collections import deque
from dataclasses import dataclass
import math


def _duration(value, name):
    value = float(value)
    if not math.isfinite(value) or value < 0:
        raise ValueError(f'{name} must be finite and nonnegative')
    return value


def _timeout(value, name):
    return None if value is None else _duration(value, name)


@dataclass(frozen=True)
class FakeChunk:
    """One immutable reply chunk, delayed from the previous chunk."""

    data: bytes
    delay: float = 0.0

    def __post_init__(self):
        object.__setattr__(self, 'data', bytes(self.data))
        object.__setattr__(self, 'delay', _duration(self.delay, 'chunk delay'))


class FakeClock:
    """A monotonic clock advanced only by explicit sleeps or transport I/O."""

    def __init__(self, start=0.0):
        self._now = float(start)
        if not math.isfinite(self._now):
            raise ValueError('clock start must be finite')

    def monotonic(self):
        return self._now

    def sleep(self, seconds):
        self.advance(seconds)

    def advance(self, seconds):
        self._now += _duration(seconds, 'clock advance')
        return self._now


class FakeSerial:
    """A small pyserial-shaped fake with one scripted reply per successful write.

    ``responses`` is an iterable of transactions. Each transaction is an
    iterable of ``FakeChunk`` objects (or bytes for zero-delay chunks). A
    single bytes value is also accepted as a one-chunk transaction. Writes
    are recorded exactly as immutable ``bytes`` values in ``writes``.

    ``timeout`` and ``write_timeout`` are mutable like pyserial's attributes.
    The delay and error controls are mutable too. Reset discards currently
    ready and scheduled input but leaves not-yet-used response transactions
    queued. No motor packets are generated by this fake.
    """

    _EMPTY_READ_STEP = 1e-6

    def __init__(
        self,
        responses=(),
        *,
        clock=None,
        timeout=0.0,
        write_timeout=0.0,
        read_delay=0.0,
        write_delay=0.0,
        reset_delay=0.0,
        write_result=None,
        read_error=None,
        write_error=None,
        reset_error=None,
    ):
        self.clock = clock if clock is not None else FakeClock()
        self.timeout = _timeout(timeout, 'timeout')
        self.write_timeout = _timeout(write_timeout, 'write_timeout')
        self.read_delay = _duration(read_delay, 'read_delay')
        self.write_delay = _duration(write_delay, 'write_delay')
        self.reset_delay = _duration(reset_delay, 'reset_delay')
        self.write_result = write_result
        self.read_error = read_error
        self.write_error = write_error
        self.reset_error = reset_error
        self._writes = []
        self._responses = deque(self._transaction(value) for value in responses)
        self._input = bytearray()
        self._scheduled = deque()

    @staticmethod
    def _chunk(value):
        if isinstance(value, FakeChunk):
            return value
        return FakeChunk(bytes(value))

    @classmethod
    def _transaction(cls, value):
        if isinstance(value, (bytes, bytearray, memoryview, FakeChunk)):
            value = (value,)
        return tuple(cls._chunk(chunk) for chunk in value)

    @property
    def writes(self):
        """Exact immutable bytes passed to every write call."""
        return tuple(self._writes)

    @property
    def in_waiting(self):
        self._release_ready()
        return len(self._input)

    def _release_ready(self):
        now = self.clock.monotonic()
        while self._scheduled and self._scheduled[0][0] <= now:
            _, data = self._scheduled.popleft()
            self._input.extend(data)

    def _schedule_response(self):
        if not self._responses:
            return
        ready_at = self.clock.monotonic()
        for chunk in self._responses.popleft():
            ready_at += chunk.delay
            self._scheduled.append((ready_at, chunk.data))
        self._release_ready()

    def reset_input_buffer(self):
        self.clock.advance(_duration(self.reset_delay, 'reset_delay'))
        if self.reset_error is not None:
            raise self.reset_error
        self._input.clear()
        self._scheduled.clear()

    def write(self, data):
        packet = bytes(data)
        self._writes.append(packet)

        delay = _duration(self.write_delay, 'write_delay')
        timeout = _timeout(self.write_timeout, 'write_timeout')
        if timeout is not None and delay > timeout:
            self.clock.advance(timeout)
            raise TimeoutError('fake serial write timed out')
        self.clock.advance(delay)
        if self.write_error is not None:
            raise self.write_error

        result = len(packet) if self.write_result is None else self.write_result
        if result == len(packet):
            self._schedule_response()
        return result

    def read(self, size=1):
        size = int(size)
        if size < 0:
            raise ValueError('read size must be nonnegative')
        if size == 0:
            return b''

        timeout = _timeout(self.timeout, 'timeout')
        remaining = timeout
        delay = _duration(self.read_delay, 'read_delay')
        if remaining is not None and delay > remaining:
            self.clock.advance(remaining)
            return b''
        self.clock.advance(delay)
        if remaining is not None:
            remaining -= delay
        if self.read_error is not None:
            raise self.read_error

        self._release_ready()
        if self._input:
            return self._take(size)

        if remaining is None:
            if self._scheduled:
                wait = max(0.0, self._scheduled[0][0] - self.clock.monotonic())
                self.clock.advance(wait)
                self._release_ready()
                if self._input:
                    return self._take(size)
            self.clock.advance(self._EMPTY_READ_STEP)
            return b''

        while remaining > 0 and self._scheduled:
            wait = max(0.0, self._scheduled[0][0] - self.clock.monotonic())
            if wait > remaining:
                self.clock.advance(remaining)
                remaining = 0.0
                break
            self.clock.advance(wait)
            remaining -= wait
            self._release_ready()
            if self._input:
                return self._take(size)

        if remaining > 0:
            self.clock.advance(remaining)
        self._release_ready()
        if self._input:
            return self._take(size)
        if timeout == 0:
            self.clock.advance(self._EMPTY_READ_STEP)
        return b''

    def _take(self, size):
        count = min(size, len(self._input))
        data = bytes(self._input[:count])
        del self._input[:count]
        return data
